def format_help_message():
    """
    Форматирует сообщение помощи с описанием всех доступных команд

    Returns:
        str: Отформатированное сообщение с командами
    """
    commands = get_bot_commands_info()

    message = "*📱 ДОСТУПНЫЕ КОМАНДЫ GUATEFIT*\n\n"

    # Группируем команды по категориям для лучшей читаемости
    categories = {
        "План питания": ["план", "план на сегодня", "полный план", "диета", "изменить план"],
        "Покупки": ["список покупок", "купил [продукт]"],
        "Трекинг": ["вес XX", "вода X", "выполнено [прием пищи]", "частично [прием пищи]",
                    "заменил [прием пищи]", "пропустил [прием пищи]"],
        "Статистика": ["статистика", "прогресс"],
        "Другое": ["помощь"]
    }

    for category, cmd_list in categories.items():
        message += f"*{category}:*\n"
        for cmd in cmd_list:
            if cmd in commands:
                message += f"• *{cmd}*: {commands[cmd]}\n"
        message += "\n"

    return message


